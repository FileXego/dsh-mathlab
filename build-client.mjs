#!/usr/bin/env node
/**
 * MathLab Web client bundler.
 *
 * Concatenates every `client-src/*.js` module (sorted by filename) into the single
 * browser artifact `client.js`, inside the exact `window.__ModuleLoader__` factory
 * wrapper documented in docs/UI.md:
 *
 *   window.__ModuleLoader__.load({
 *     id: 'dsh-mathlab',
 *     factory(require) { ... return ML.plugin; },
 *   });
 *
 * Module files are plain JavaScript (no JSX, no `import`/`export`, no bundler syntax).
 * They share the factory scope, so every module wraps itself in an IIFE and attaches
 * what it provides to the single `ML` object.
 *
 * Usage:  node build-client.mjs
 * Gate:   node --check client.js
 */
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const srcDir = join(root, 'client-src');
const outFile = join(root, 'client.js');

const FORBIDDEN = [
  { name: 'ES import statement', re: /^[ \t]*import[ \t]+[\w{*'"]/m },
  { name: 'ES export statement', re: /^[ \t]*export[ \t]+(?:default|const|let|var|function|class|\{|\*)/m },
  { name: 'require() call inside a module (use the outer factory scope)', re: /\brequire\s*\(/ },
  { name: 'dynamic import()', re: /\bimport\s*\(/ },
  { name: 'JSX-looking arrow body', re: /=>\s*\(\s*<[A-Z]/ },
  { name: 'JSX-looking return', re: /\breturn\s*\(\s*<[A-Z]/ },
  { name: 'JSX-looking expression', re: /=\s*<[A-Z][\w.]*\s*[\s/>]/ },
];

let files;
try {
  files = (await readdir(srcDir)).filter((f) => f.endsWith('.js')).sort();
} catch (error) {
  console.error(`[build-client] cannot read ${srcDir}: ${error.message}`);
  process.exit(1);
}
if (files.length === 0) {
  console.error('[build-client] client-src has no .js modules');
  process.exit(1);
}

const problems = [];
const parts = [];
for (const file of files) {
  const text = await readFile(join(srcDir, file), 'utf8');
  for (const rule of FORBIDDEN) {
    if (rule.re.test(text)) problems.push(`${file}: ${rule.name}`);
  }
  parts.push(`// ===== client-src/${file} =====\n${text.trimEnd()}\n`);
}

const body = parts.join('\n');
if (!/\bML\.plugin\s*=/.test(body)) {
  problems.push('no `ML.plugin =` assignment found (90-root.js must define the plugin)');
}
if (problems.length > 0) {
  console.error('[build-client] refusing to build:');
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

const banner = [
  '/*! MathLab Web client for DeepSeek Harness.',
  ' *  Generated by build-client.mjs from client-src/*.js — do not edit client.js directly.',
  ' *  Registration shape: window.__ModuleLoader__.load({ id: "dsh-mathlab", factory(require) {...} }).',
  ' */',
].join('\n');

const out = `${banner}
window.__ModuleLoader__.load({
  id: 'dsh-mathlab',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const ML = { React, h, NS: 'dsh-mathlab', DICT: {} };
${body}    return ML.plugin;
  },
});
`;

/**
 * Trim documentation comments from the generated artifact only (sources keep them).
 * Whole-line comments and blank runs are removed; code, strings and CSS text are
 * left untouched, so behavior is identical while the delivered bundle stays lean.
 */
const compact = (text) =>
  text
    .replace(/^[ \t]*\/\*[\s\S]*?\*\/[ \t]*$/gm, '')
    .replace(/^[ \t]*\/\/[^\n]*$/gm, '')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n');
const artifact = compact(out);

const LIMIT = 620 * 1024;
const bytes = Buffer.byteLength(artifact, 'utf8');
if (bytes > LIMIT) {
  console.error(`[build-client] output is ${(bytes / 1024).toFixed(1)} KB, above the ${LIMIT / 1024} KB budget`);
  process.exit(1);
}
await writeFile(outFile, artifact, 'utf8');
const info = await stat(outFile);
console.log(`[build-client] client.js written: ${(info.size / 1024).toFixed(1)} KB from ${files.length} modules`);
for (const file of files) console.log('  + ' + file);
